import psycopg
from flask import Flask, request, jsonify

from database.database import get_connection
from database.repositories.user_repo import UserRepo
from services import user_service, auth_service

app = Flask(__name__)

@app.route("/signup", methods=["POST"])
def signup():
    data = request.get_json()
    repo = UserRepo(get_connection())
    try:
        user = user_service.signup(
            repo,
            username=data.get("username"),
            email=data.get("email"),
            firstname=data.get("first_name"),
            lastname=data.get("last_name"),
            plain_password=data.get("password"),
        )
        return jsonify(user.to_public_dict()), 201
    except ValueError as e:
        return jsonify({"error": str(e.args[0])})
    except psycopg.errors.UniqueViolation as e:
        constraint = e.diag.constraint_name
        if constraint == "users_username_key":
            return jsonify({"error": {"username": "Username already in use"}}), 409
        elif constraint == "users_email_key":
            return jsonify({"error": {"email": "Email already in use"}}), 409
        else:
            return jsonify({"error": "A uniqueness constraint was violated"}), 409

